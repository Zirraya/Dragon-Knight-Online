    internal static CharacterStats For(int template, int level)
    {
        int index = template switch { 1 or 6 => 0, 2 or 7 => 1, 3 or 8 => 2, 4 or 9 => 3, 5 or 10 => 4, _ => 0 };
        int levelIndex = Math.Clamp(level, 1, MaxLevel) - 1;
        return Stats[index][levelIndex];
    }

    internal static int LevelForExperience(int experience)
    {
        int level = 1;
        while (level < MaxLevel && experience >= ExperienceThresholds[level])
            level++;
        return level;
    }

    internal static int ExperienceForLevel(int level) => ExperienceThresholds[Math.Clamp(level, 1, MaxLevel) - 1];

    internal static int ExperienceWithinLevel(int totalExperience, int level) =>
        Math.Max(0, totalExperience - ExperienceForLevel(level));

    internal static int ExperienceToNextLevel(int level) => level >= MaxLevel
        ? 0
        : ExperienceThresholds[level] - ExperienceThresholds[level - 1];
